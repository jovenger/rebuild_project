-- Essais du bandeau des messages (fiche 00_bandeau.md).

local bandeau = Scriptorium.bandeau

essai("bandeau : une nouvelle s'affiche au battement, puis s'efface après sa durée", function()
  depart()
  egal(bandeau.annoncer("ui_scriptorium_essai_nouvelle"), "en_file", "sort")
  egal(bandeau.en_attente(), 1, "en attente")
  local en_cours = bandeau.battre()
  verifier(en_cours ~= nil, "affichage en cours")
  egal(FauxJeu.en_ecran, "@ui_scriptorium_essai_nouvelle", "texte à l'écran, précédé de @")
  egal(FauxJeu.affichages[1].duree, bandeau.reglages.duree_par_defaut, "durée par défaut")
  FauxJeu.avancer(bandeau.reglages.duree_par_defaut - 1)
  bandeau.battre()
  egal(FauxJeu.en_ecran, "@ui_scriptorium_essai_nouvelle", "toujours à l'écran avant la fin")
  FauxJeu.avancer(1)
  bandeau.battre()
  egal(FauxJeu.en_ecran, nil, "effacé à la fin")
  egal(bandeau.en_cours(), nil, "plus rien en cours")
end)

essai("bandeau : un seul message à la fois, dans l'ordre", function()
  depart()
  bandeau.annoncer("ui_scriptorium_essai_nouvelle")
  bandeau.annoncer("ui_scriptorium_essai_registre")
  bandeau.battre()
  egal(FauxJeu.en_ecran, "@ui_scriptorium_essai_nouvelle", "premier")
  FauxJeu.avancer(1)
  bandeau.battre()
  egal(FauxJeu.en_ecran, "@ui_scriptorium_essai_nouvelle", "le second attend")
  FauxJeu.avancer(10)
  bandeau.battre()
  egal(FauxJeu.en_ecran, "@ui_scriptorium_essai_registre", "second après le premier")
  egal(#FauxJeu.affichages, 2, "deux affichages")
end)

essai("bandeau : une alerte passe devant les nouvelles, mais pas devant une autre alerte", function()
  depart()
  bandeau.annoncer("ui_scriptorium_essai_nouvelle")
  bandeau.annoncer("ui_scriptorium_essai_registre")
  bandeau.annoncer("ui_scriptorium_essai_alerte", { importance = "alerte" })
  bandeau.annoncer("ui_scriptorium_socle_pret", { importance = "alerte" })
  local ordre = {}
  for _ = 1, 4 do
    bandeau.battre()
    table.insert(ordre, FauxJeu.en_ecran)
    FauxJeu.avancer(10)
    bandeau.battre()
  end
  egal(ordre[1], "@ui_scriptorium_essai_alerte", "1re : alerte")
  egal(ordre[2], "@ui_scriptorium_socle_pret", "2e : seconde alerte, derrière la première")
  egal(ordre[3], "@ui_scriptorium_essai_nouvelle", "3e : nouvelle")
  egal(ordre[4], "@ui_scriptorium_essai_registre", "4e : nouvelle")
end)

essai("bandeau : un même message n'est pas redit avant le délai de répétition", function()
  depart()
  egal(bandeau.annoncer("ui_scriptorium_essai_nouvelle"), "en_file", "première fois")
  egal(bandeau.annoncer("ui_scriptorium_essai_nouvelle"), "repete", "tout de suite après : repoussé")
  FauxJeu.avancer(bandeau.reglages.delai_repetition - 1)
  egal(bandeau.annoncer("ui_scriptorium_essai_nouvelle"), "repete", "juste avant le délai : repoussé")
  FauxJeu.avancer(1)
  egal(bandeau.annoncer("ui_scriptorium_essai_nouvelle"), "en_file", "après le délai : accepté")
  egal(bandeau.comptes().repetes, 2, "deux répétitions comptées")
end)

essai("bandeau : les messages d'un même groupe en attente se regroupent en un seul", function()
  depart()
  local options = { groupe = "arrivee", cle_plusieurs = "ui_scriptorium_essai_arrivee_plusieurs" }
  egal(bandeau.annoncer("ui_scriptorium_essai_arrivee", options), "en_file", "premier")
  egal(bandeau.annoncer("ui_scriptorium_essai_arrivee", options), "regroupe", "deuxième")
  egal(bandeau.annoncer("ui_scriptorium_essai_arrivee", options), "regroupe", "troisième")
  egal(bandeau.en_attente(), 1, "un seul message en attente")
  bandeau.battre()
  egal(FauxJeu.en_ecran, "@ui_scriptorium_essai_arrivee_plusieurs", "texte du groupe")
  egal(bandeau.historique()[1].nombre, 3, "trois comptés")
end)

essai("bandeau : sans clé groupée, le groupe garde le texte simple", function()
  depart()
  bandeau.annoncer("ui_scriptorium_essai_arrivee", { groupe = "arrivee" })
  bandeau.annoncer("ui_scriptorium_essai_arrivee", { groupe = "arrivee" })
  bandeau.battre()
  egal(FauxJeu.en_ecran, "@ui_scriptorium_essai_arrivee", "texte simple")
end)

essai("bandeau : pendant un dialogue, le message attend", function()
  depart()
  bandeau.annoncer("ui_scriptorium_essai_nouvelle")
  FauxJeu.dialogue = true
  egal(bandeau.battre(), nil, "rien pendant le dialogue")
  egal(FauxJeu.en_ecran, nil, "écran vide")
  FauxJeu.dialogue = false
  verifier(bandeau.battre() ~= nil, "affiché après le dialogue")
end)

essai("bandeau : la durée est bornée entre le minimum et le maximum", function()
  depart()
  bandeau.annoncer("ui_scriptorium_essai_nouvelle", { duree = 1 })
  bandeau.battre()
  egal(FauxJeu.affichages[1].duree, bandeau.reglages.duree_min, "trop court -> minimum")
  FauxJeu.avancer(100)
  bandeau.battre()
  bandeau.annoncer("ui_scriptorium_essai_registre", { duree = 60 })
  bandeau.battre()
  egal(FauxJeu.affichages[2].duree, bandeau.reglages.duree_max, "trop long -> maximum")
end)

essai("bandeau : l'importance « journal » ne va jamais à l'écran", function()
  depart()
  egal(bandeau.annoncer("ui_scriptorium_essai_nouvelle", { importance = "journal" }), "journal", "sort")
  egal(bandeau.en_attente(), 0, "rien en file")
  egal(bandeau.battre(), nil, "rien à l'écran")
  egal(#FauxJeu.journal_lignes, 1, "une ligne au journal")
  egal(bandeau.historique()[1].sort, "journal", "dans l'historique")
end)

essai("bandeau : une clé mal formée ou une importance inconnue sont refusées, sans erreur", function()
  depart()
  egal(bandeau.annoncer("Raid en vue !"), "refuse", "texte brut refusé")
  egal(bandeau.annoncer("ui_autre_chose"), "refuse", "clé hors du socle refusée")
  egal(bandeau.annoncer(nil), "refuse", "nil refusé")
  egal(bandeau.annoncer("ui_scriptorium_essai_nouvelle", { importance = "urgent" }), "refuse", "importance inconnue")
  egal(bandeau.annoncer("ui_scriptorium_essai_nouvelle", { cle_plusieurs = "n'importe quoi" }), "refuse", "clé groupée mal formée")
  egal(bandeau.comptes().refuses, 5, "cinq refus comptés")
  egal(bandeau.en_attente(), 0, "rien en file")
end)

essai("bandeau : l'historique garde les derniers messages, pas plus que la taille réglée", function()
  depart()
  local taille = bandeau.reglages.taille_historique
  for i = 1, taille + 5 do
    bandeau.annoncer("ui_scriptorium_essai_nouvelle", { importance = "journal" })
  end
  egal(#bandeau.historique(), taille, "taille bornée")
end)

essai("bandeau : demarrer() fait battre le bandeau par la minuterie du jeu, arreter() l'arrête", function()
  depart()
  bandeau.demarrer()
  egal(#FauxJeu.minuteries, 1, "une minuterie posée")
  egal(FauxJeu.minuteries[1].ms, bandeau.reglages.cadence_ms, "à la cadence réglée")
  bandeau.annoncer("ui_scriptorium_essai_nouvelle")
  FauxJeu.tic_minuterie()
  egal(FauxJeu.en_ecran, "@ui_scriptorium_essai_nouvelle", "affiché au tic")
  egal(#FauxJeu.minuteries, 1, "la minuterie se repose")
  bandeau.demarrer()
  egal(#FauxJeu.minuteries, 1, "un second demarrer() ne double pas la minuterie")
  bandeau.arreter()
  FauxJeu.tic_minuterie()
  egal(#FauxJeu.minuteries, 0, "arrêté : plus de minuterie")
end)
