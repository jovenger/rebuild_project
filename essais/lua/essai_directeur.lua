    disponible = function() return false, "non" end, agir = function() return true end })
  egal(#directeur.menu(), 13, "remplacée, pas doublée")
  egal(entree(directeur.menu(), "essai_entree").raison, "non", "remplacée")
  directeur.retirer_entrees()
